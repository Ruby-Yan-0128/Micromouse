/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  if (dfu_boot_flag == DFU_MAGIC_KEY) {
    dfu_boot_flag = 0;
    void (*SysMemBootJump)(void) = (void (*)(void))(*((uint32_t *)0x1FFF0004));
    __set_MSP(*((uint32_t *)0x1FFF0000));
    SysMemBootJump();
    while (1);
}


  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USB_DEVICE_Init();
  MX_TIM1_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  /* USER CODE BEGIN 2 */
HAL_TIM_Encoder_Start(&htim1, TIM_CHANNEL_ALL);
HAL_TIM_Encoder_Start(&htim3, TIM_CHANNEL_ALL);
resetEncoders();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    left_counts = getLeftEncoderCounts();
    right_counts = getRightEncoderCounts();

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    static uint32_t last_tx = 0;
    char buf[512];
    if (HAL_GetTick() - last_tx >= 50) {
        last_tx = HAL_GetTick();
        int n = snprintf(buf, sizeof(buf), ">left:%d\n>right:%d\n",
                        left_counts, right_counts);
        CDC_Transmit_FS((uint8_t *) buf, (uint16_t) n);
    }

    if (buttonPressed) {
        uint32_t currentTime = HAL_GetTick();
        if (currentTime - pressTime >= 1000) { // 1 second
            dfu_boot_flag = DFU_MAGIC_KEY;
            HAL_NVIC_SystemReset();
        }
    }
  }
  /* USER CODE END 3 */
}

